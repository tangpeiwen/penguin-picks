#!/usr/bin/env python3
"""Build the mini-program's locally embedded display-font subset."""

from __future__ import annotations

import argparse
import base64
import shutil
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MINIPROGRAM = ROOT / "miniprogram"
GENERATED_WXSS = MINIPROGRAM / "styles" / "fonts.wxss"
BUILD_DIR = ROOT / "tmp" / "font-subset"
SOURCE_SUFFIXES = {".js", ".json", ".wxml", ".wxss"}


def collect_characters() -> str:
    characters: set[str] = set()
    for path in MINIPROGRAM.rglob("*"):
        if not path.is_file() or path.suffix not in SOURCE_SUFFIXES:
            continue
        if path == GENERATED_WXSS:
            continue
        characters.update(path.read_text(encoding="utf-8"))

    # Keep common punctuation available for future short labels.
    characters.update("，。！？：；、（）【】《》“”‘’—…·～￥→+/-0123456789")
    return "".join(sorted(characters))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source_font", type=Path)
    args = parser.parse_args()

    subsetter = shutil.which("pyftsubset")
    if not subsetter:
        raise SystemExit("pyftsubset was not found; install fonttools first")
    if not args.source_font.is_file():
        raise SystemExit(f"Font file not found: {args.source_font}")

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED_WXSS.parent.mkdir(parents=True, exist_ok=True)
    charset_file = BUILD_DIR / "characters.txt"
    subset_file = BUILD_DIR / "lemi-xiao-naipao-subset.woff"
    charset_file.write_text(collect_characters(), encoding="utf-8")

    subprocess.run(
        [
            subsetter,
            str(args.source_font),
            f"--text-file={charset_file}",
            f"--output-file={subset_file}",
            "--flavor=woff",
            "--layout-features=*",
            "--name-IDs=*",
            "--name-languages=*",
            "--notdef-glyph",
            "--notdef-outline",
            "--recommended-glyphs",
        ],
        check=True,
    )

    encoded = base64.b64encode(subset_file.read_bytes()).decode("ascii")
    GENERATED_WXSS.write_text(
        "/* Generated by tools/build_font_asset.py. Do not edit by hand. */\n"
        "@font-face {\n"
        '  font-family: "LemiXiaoNaiPao";\n'
        f'  src: url("data:font/woff;base64,{encoded}") format("woff");\n'
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        "}\n",
        encoding="utf-8",
    )

    print(f"Characters: {len(charset_file.read_text(encoding='utf-8'))}")
    print(f"Subset: {subset_file.stat().st_size / 1024:.1f} KiB")
    print(f"Generated WXSS: {GENERATED_WXSS.stat().st_size / 1024:.1f} KiB")


if __name__ == "__main__":
    main()
