#!/usr/bin/env python3
"""Build the mini-program's locally embedded display-font subset."""

from __future__ import annotations

import argparse
import base64
import json
import shutil
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MINIPROGRAM = ROOT / "miniprogram"
GENERATED_WXSS = MINIPROGRAM / "styles" / "fonts.wxss"
STATIC_WXSS = MINIPROGRAM / "styles" / "font-static.wxss"
RESTAURANT_WXSS = MINIPROGRAM / "styles" / "font-restaurants.wxss"
BUILD_DIR = ROOT / "tmp" / "font-subset"
SOURCE_SUFFIXES = {".js", ".json", ".wxml", ".wxss"}
RESTAURANT_DATA = MINIPROGRAM / "data" / "restaurants.js"
MAX_EMBEDDED_RESOURCE_BYTES = 200 * 1024


def restaurant_display_text() -> str:
    """Collect only dynamic values that are actually rendered with the display font."""
    source = RESTAURANT_DATA.read_text(encoding="utf-8")
    payload = source.split("module.exports = ", 1)[1].strip().rstrip(";")
    restaurants = json.loads(payload)
    return "".join(
        restaurant.get("name", "") + "".join(restaurant.get("cuisines", []))
        for restaurant in restaurants
    )


def collect_character_sets() -> tuple[str, str]:
    characters: set[str] = set()
    for path in MINIPROGRAM.rglob("*"):
        if not path.is_file() or path.suffix not in SOURCE_SUFFIXES:
            continue
        if path in {GENERATED_WXSS, STATIC_WXSS, RESTAURANT_WXSS, RESTAURANT_DATA}:
            continue
        characters.update(path.read_text(encoding="utf-8"))

    # Keep common punctuation available for future short labels.
    characters.update("，。！？：；、（）【】《》“”‘’—…·～￥→+/-0123456789")
    restaurant_characters = set(restaurant_display_text()) - characters
    return "".join(sorted(characters)), "".join(sorted(restaurant_characters))


def build_subset(subsetter: str, source_font: Path, key: str, family: str, characters: str, target: Path) -> tuple[int, int]:
    charset_file = BUILD_DIR / f"characters-{key}.txt"
    subset_file = BUILD_DIR / f"lemi-xiao-naipao-{key}.woff2"
    charset_file.write_text(characters, encoding="utf-8")
    subprocess.run(
        [
            subsetter,
            str(source_font),
            f"--text-file={charset_file}",
            f"--output-file={subset_file}",
            "--flavor=woff2",
            "--layout-features=",
            "--name-IDs=0,1,2,3,4,5,6",
            "--name-languages=0x409",
            "--notdef-glyph",
            "--notdef-outline",
            "--recommended-glyphs",
        ],
        check=True,
    )
    encoded = base64.b64encode(subset_file.read_bytes()).decode("ascii")
    target.write_text(
        "/* Generated by tools/build_font_asset.py. Do not edit by hand. */\n"
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        f'  src: url("data:font/woff2;base64,{encoded}") format("woff2");\n'
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        "}\n",
        encoding="utf-8",
    )
    resource_size = target.stat().st_size
    if resource_size > MAX_EMBEDDED_RESOURCE_BYTES:
        raise SystemExit(f"Generated font shard exceeds 200 KiB: {target} ({resource_size / 1024:.1f} KiB)")
    return len(characters), subset_file.stat().st_size


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source_font", type=Path)
    args = parser.parse_args()

    subsetter = shutil.which("pyftsubset")
    if not subsetter:
        raise SystemExit("pyftsubset was not found; install fonttools first")
    if not args.source_font.is_file():
        raise SystemExit(f"Font file not found: {args.source_font}")

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED_WXSS.parent.mkdir(parents=True, exist_ok=True)
    static_characters, restaurant_characters = collect_character_sets()
    static_count, static_size = build_subset(
        subsetter, args.source_font, "static", "LemiXiaoNaiPaoStatic", static_characters, STATIC_WXSS
    )
    restaurant_count, restaurant_size = build_subset(
        subsetter, args.source_font, "restaurants", "LemiXiaoNaiPaoRestaurants", restaurant_characters, RESTAURANT_WXSS
    )
    GENERATED_WXSS.write_text(
        "/* Generated by tools/build_font_asset.py. Do not edit by hand. */\n"
        '@import "./font-static.wxss";\n'
        '@import "./font-restaurants.wxss";\n',
        encoding="utf-8",
    )

    print(f"Static characters: {static_count}; WOFF2: {static_size / 1024:.1f} KiB; WXSS: {STATIC_WXSS.stat().st_size / 1024:.1f} KiB")
    print(f"Restaurant-only characters: {restaurant_count}; WOFF2: {restaurant_size / 1024:.1f} KiB; WXSS: {RESTAURANT_WXSS.stat().st_size / 1024:.1f} KiB")


if __name__ == "__main__":
    main()
